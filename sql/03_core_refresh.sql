    SUPPLIER_ID,
    PART_ID,
    LEAD_TIME_DAYS,
    CONTRACTED_UNIT_COST_USD,
    MINIMUM_ORDER_QUANTITY,
    PRIMARY_SUPPLIER_FLAG
