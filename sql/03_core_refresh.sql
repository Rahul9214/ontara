-- Ontara deterministic RAW -> CORE refresh
--
-- Purpose:
--   1. Reload the deterministic staged CSV dataset into RAW.
--   2. Convert source-preserving VARCHAR values into governed CORE types.
--   3. Produce explicit row-count evidence for both layers.
--
-- This script is intentionally rerunnable:
--   - RAW tables are truncated before COPY.
--   - CORE tables are truncated before typed inserts.
--   - COPY aborts on malformed input.
--
-- Expected deterministic row counts:
--   suppliers             8
--   parts                12
--   plants                4
--   supplier_parts       23
--   purchase_orders      24
--   customers            10
--   customer_orders      30
--   shipments            32
--   shipment_events     192
--   inventory_snapshots  48


USE ROLE ONTARA_DEV_ROLE;
USE WAREHOUSE ONTARA_WH;
USE DATABASE ONTARA;


-- ===========================================================================
-- PHASE 1: RESET RAW
-- ===========================================================================

TRUNCATE TABLE ONTARA.RAW.SUPPLIERS;
TRUNCATE TABLE ONTARA.RAW.PARTS;
TRUNCATE TABLE ONTARA.RAW.PLANTS;
TRUNCATE TABLE ONTARA.RAW.SUPPLIER_PARTS;
TRUNCATE TABLE ONTARA.RAW.PURCHASE_ORDERS;
TRUNCATE TABLE ONTARA.RAW.CUSTOMERS;
TRUNCATE TABLE ONTARA.RAW.CUSTOMER_ORDERS;
TRUNCATE TABLE ONTARA.RAW.SHIPMENTS;
TRUNCATE TABLE ONTARA.RAW.SHIPMENT_EVENTS;
TRUNCATE TABLE ONTARA.RAW.INVENTORY_SNAPSHOTS;


-- ===========================================================================
-- PHASE 2: LOAD DETERMINISTIC CSV FILES INTO RAW
-- ===========================================================================

COPY INTO ONTARA.RAW.SUPPLIERS
FROM @ONTARA.RAW.SYNTHETIC_STAGE/suppliers.csv.gz
FILE_FORMAT = (FORMAT_NAME = 'ONTARA.RAW.ONTARA_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO ONTARA.RAW.PARTS
FROM @ONTARA.RAW.SYNTHETIC_STAGE/parts.csv.gz
FILE_FORMAT = (FORMAT_NAME = 'ONTARA.RAW.ONTARA_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO ONTARA.RAW.PLANTS
FROM @ONTARA.RAW.SYNTHETIC_STAGE/plants.csv.gz
FILE_FORMAT = (FORMAT_NAME = 'ONTARA.RAW.ONTARA_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO ONTARA.RAW.SUPPLIER_PARTS
FROM @ONTARA.RAW.SYNTHETIC_STAGE/supplier_parts.csv.gz
FILE_FORMAT = (FORMAT_NAME = 'ONTARA.RAW.ONTARA_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO ONTARA.RAW.PURCHASE_ORDERS
FROM @ONTARA.RAW.SYNTHETIC_STAGE/purchase_orders.csv.gz
FILE_FORMAT = (FORMAT_NAME = 'ONTARA.RAW.ONTARA_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO ONTARA.RAW.CUSTOMERS
FROM @ONTARA.RAW.SYNTHETIC_STAGE/customers.csv.gz
FILE_FORMAT = (FORMAT_NAME = 'ONTARA.RAW.ONTARA_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO ONTARA.RAW.CUSTOMER_ORDERS
FROM @ONTARA.RAW.SYNTHETIC_STAGE/customer_orders.csv.gz
FILE_FORMAT = (FORMAT_NAME = 'ONTARA.RAW.ONTARA_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO ONTARA.RAW.SHIPMENTS
FROM @ONTARA.RAW.SYNTHETIC_STAGE/shipments.csv.gz
FILE_FORMAT = (FORMAT_NAME = 'ONTARA.RAW.ONTARA_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO ONTARA.RAW.SHIPMENT_EVENTS
FROM @ONTARA.RAW.SYNTHETIC_STAGE/shipment_events.csv.gz
FILE_FORMAT = (FORMAT_NAME = 'ONTARA.RAW.ONTARA_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO ONTARA.RAW.INVENTORY_SNAPSHOTS
FROM @ONTARA.RAW.SYNTHETIC_STAGE/inventory_snapshots.csv.gz
FILE_FORMAT = (FORMAT_NAME = 'ONTARA.RAW.ONTARA_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';


-- ===========================================================================
-- PHASE 3: VERIFY RAW ROW COUNTS
-- ===========================================================================

SELECT 'SUPPLIERS' AS TABLE_NAME, COUNT(*) AS ROW_COUNT
FROM ONTARA.RAW.SUPPLIERS

UNION ALL

SELECT 'PARTS', COUNT(*)
FROM ONTARA.RAW.PARTS

UNION ALL

SELECT 'PLANTS', COUNT(*)
FROM ONTARA.RAW.PLANTS

UNION ALL

SELECT 'SUPPLIER_PARTS', COUNT(*)
FROM ONTARA.RAW.SUPPLIER_PARTS

UNION ALL

SELECT 'PURCHASE_ORDERS', COUNT(*)
FROM ONTARA.RAW.PURCHASE_ORDERS

UNION ALL

SELECT 'CUSTOMERS', COUNT(*)
FROM ONTARA.RAW.CUSTOMERS

UNION ALL

SELECT 'CUSTOMER_ORDERS', COUNT(*)
FROM ONTARA.RAW.CUSTOMER_ORDERS

UNION ALL

SELECT 'SHIPMENTS', COUNT(*)
FROM ONTARA.RAW.SHIPMENTS

UNION ALL

SELECT 'SHIPMENT_EVENTS', COUNT(*)
FROM ONTARA.RAW.SHIPMENT_EVENTS

UNION ALL

SELECT 'INVENTORY_SNAPSHOTS', COUNT(*)
FROM ONTARA.RAW.INVENTORY_SNAPSHOTS

