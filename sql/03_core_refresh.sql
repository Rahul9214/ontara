-- ===========================================================================
-- PHASE 5: GOVERNED TYPE CONVERSION INTO CORE
-- ===========================================================================


-- Supplier

INSERT INTO ONTARA.CORE.SUPPLIERS (
    SUPPLIER_ID,
    SUPPLIER_NAME,
    COUNTRY_CODE,
    RISK_TIER,
    STATUS
)
SELECT
    SUPPLIER_ID,
    SUPPLIER_NAME,
    COUNTRY_CODE,
    RISK_TIER,
    STATUS
FROM ONTARA.RAW.SUPPLIERS;


-- Part

INSERT INTO ONTARA.CORE.PARTS (
    PART_ID,
    PART_NAME,
    CATEGORY,
    UNIT_OF_MEASURE,
    STANDARD_UNIT_COST_USD
)
SELECT
    PART_ID,
    PART_NAME,
    CATEGORY,
    UNIT_OF_MEASURE,
    TO_DECIMAL(STANDARD_UNIT_COST_USD, 18, 2)
FROM ONTARA.RAW.PARTS;


-- Plant

